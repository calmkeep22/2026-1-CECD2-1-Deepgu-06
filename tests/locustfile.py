"""Short local load smoke tests for the backend and MediaMTX endpoints."""

import os
import random

from locust import HttpUser, between, task


BACKEND_URL = os.getenv("LOAD_BACKEND_URL", "http://127.0.0.1:18000")
HLS_URL = os.getenv("LOAD_HLS_URL", "http://127.0.0.1:18888")
WEBRTC_URL = os.getenv("LOAD_WEBRTC_URL", "http://127.0.0.1:8889")
EMAIL = os.getenv("LOAD_TEST_EMAIL", "loadtest@example.com")
PASSWORD = os.getenv("LOAD_TEST_PASSWORD", "loadtest-password")
CAMERA_IDS = [value for value in os.getenv("LOAD_CAMERA_IDS", "load-camera-1").split(",") if value]
STREAM_KEYS = [value for value in os.getenv("LOAD_STREAM_KEYS", "load-stream-1").split(",") if value]


class FEPollingUser(HttpUser):
    """Authenticated API traffic generated by the streaming frontend."""

    host = BACKEND_URL
    fixed_count = int(os.getenv("LOAD_API_USERS", "5"))
    wait_time = between(0.5, 1.5)

    def on_start(self):
        with self.client.post(
            "/api/auth/login",
            json={"email": EMAIL, "password": PASSWORD},
            name="POST /api/auth/login",
            catch_response=True,
        ) as response:
            if response.status_code != 200:
                response.failure(f"login failed: {response.status_code} {response.text[:200]}")
                return

            token = response.json()["data"]["access_token"]
            self.client.headers.update({"Authorization": f"Bearer {token}"})

    @task(4)
    def poll_stream_status(self):
        camera_id = random.choice(CAMERA_IDS)
        self.client.get(
            f"/api/cameras/{camera_id}/stream",
            name="GET /api/cameras/[id]/stream",
        )

    @task(2)
    def get_cameras(self):
        self.client.get("/api/cameras", name="GET /api/cameras")

    @task(1)
    def get_events(self):
        self.client.get("/api/events?page=1&size=20", name="GET /api/events")


class MediaPlaybackProbeUser(HttpUser):
    """HLS traffic plus a WebRTC signalling-page availability probe.

    The WebRTC request does not pretend to be a real WebRTC peer and is
    reported separately from the HLS requests.
    """

    host = HLS_URL
    fixed_count = int(os.getenv("LOAD_MEDIA_USERS", "3"))
    wait_time = between(0.5, 1.5)

    @task(4)
    def get_hls_manifest(self):
        stream_key = random.choice(STREAM_KEYS)
        self.client.get(
            f"/live/{stream_key}/index.m3u8",
            name="GET HLS /live/[key]/index.m3u8",
            allow_redirects=True,
        )

    @task(1)
    def get_webrtc_player_page(self):
        stream_key = random.choice(STREAM_KEYS)
        with self.client.get(
            f"{WEBRTC_URL}/live/{stream_key}/",
            name="GET WebRTC /live/[key]/",
            catch_response=True,
        ) as response:
            if response.status_code != 200 or "<video" not in response.text:
                response.failure(f"WebRTC player page unavailable: {response.status_code}")
